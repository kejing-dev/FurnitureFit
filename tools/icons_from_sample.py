#!/usr/bin/env python
"""Turns the <symbol> icons of the approved sample (design package iconSet) into VectorDrawables.

    python tools/icons_from_sample.py <sample.html>

Strokes stay strokes (white; the Icon composable tints them). <rect>/<circle> become paths; the
"90" of the rotate icon and the cut-out of the warning triangle are drawn by hand (no <text>).
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable")

NAMES = {
    "i-undo": "ic_undo", "i-more": "ic_more", "i-solid": "ic_look_solid", "i-wire": "ic_look_wire",
    "i-rot": "ic_rotate90", "i-trash": "ic_trash", "i-close": "ic_close", "i-check": "ic_check",
    "i-warn": "ic_warning", "i-hit": "ic_hit", "i-globe": "ic_globe", "i-exit": "ic_exit",
    "i-retry": "ic_retry", "i-lost": "ic_unavailable", "i-back": "ic_backspace",
    "t-sofa3": "fu_sofa3", "t-sofa2": "fu_sofa2", "t-armchair": "fu_armchair", "t-bedDouble": "fu_bed_double",
    "t-bedSingle": "fu_bed_single", "t-dining": "fu_dining", "t-desk": "fu_desk", "t-bookcase": "fu_bookcase",
    "t-wardrobe": "fu_wardrobe", "t-tvStand": "fu_tv_stand", "t-custom": "fu_custom",
}


def attr(tag, name, default=None):
    m = re.search(r'\b%s="([^"]*)"' % re.escape(name), tag)
    return m.group(1) if m else default


def rect_path(tag):
    x, y, w, h = (float(attr(tag, k, "0")) for k in ("x", "y", "width", "height"))
    rx = float(attr(tag, "rx", "0"))
    if rx <= 0:
        return "M%g,%gh%gv%gh%gZ" % (x, y, w, h, -w)
    return ("M%g,%gh%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%g h%g a%g,%g 0 0 1 %g,%g v%g a%g,%g 0 0 1 %g,%gZ"
            % (x + rx, y, w - 2 * rx, rx, rx, rx, rx, h - 2 * rx, rx, rx, -rx, rx, -(w - 2 * rx), rx, rx, -rx, -rx,
               -(h - 2 * rx), rx, rx, rx, -rx))


def circle_path(tag):
    cx, cy, r = (float(attr(tag, k, "0")) for k in ("cx", "cy", "r"))
    return "M%g,%ga%g,%g 0 1 0 %g,0a%g,%g 0 1 0 %g,0Z" % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)


def vector(size, paths):
    body = []
    for p in paths:
        d, fill, stroke, width, cap, join, even = p
        a = ['android:pathData="%s"' % d]
        if fill:
            a.append('android:fillColor="#FFFFFFFF"')
            if even:
                a.append('android:fillType="evenOdd"')
        if stroke:
            a += ['android:strokeColor="#FFFFFFFF"', 'android:strokeWidth="%s"' % width,
                  'android:strokeLineCap="%s"' % cap, 'android:strokeLineJoin="%s"' % join]
        body.append("    <path\n        " + "\n        ".join(a) + " />")
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tools/icons_from_sample.py from the approved sample -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="%ddp"\n    android:height="%ddp"\n'
            '    android:viewportWidth="%d"\n    android:viewportHeight="%d">\n%s\n</vector>\n') % (size, size, size, size, "\n".join(body))


def main(sample):
    html = open(sample, encoding="utf-8").read()
    for m in re.finditer(r'<symbol id="([^"]+)" viewBox="0 0 (\d+) (\d+)">(.*?)</symbol>', html, re.S):
        sid, size, inner = m.group(1), int(m.group(2)), m.group(4)
        name = NAMES.get(sid)
        if not name:
            continue
        group = re.search(r"<g([^>]*)>", inner)
        g = group.group(1) if group else ""
        paths = []
        for el in re.finditer(r"<(path|rect|circle)\b([^>]*)/?>", inner):
            kind, tag = el.group(1), el.group(2)
            d = attr(tag, "d") if kind == "path" else rect_path(tag) if kind == "rect" else circle_path(tag)
            fill = attr(tag, "fill", attr(g, "fill", "currentColor"))
            stroke = attr(tag, "stroke", attr(g, "stroke"))
            if stroke and "var(" in stroke:
                continue  # the warning's exclamation: cut out below
            width = attr(tag, "stroke-width", attr(g, "stroke-width", "2"))
            cap = attr(tag, "stroke-linecap", attr(g, "stroke-linecap", "butt"))
            join = attr(tag, "stroke-linejoin", attr(g, "stroke-linejoin", "miter"))
            paths.append([d, fill not in (None, "none"), stroke not in (None, "none"), width, cap, join, False])
        if sid == "i-warn":
            paths = [["M12,4L22,20H2Z M10.9,9.6h2.2v5.4h-2.2Z M10.9,16.4h2.2v2h-2.2Z", True, False, "0", "round", "round", True]]
        if sid == "i-rot":
            # the "90": a nine and a zero as strokes
            paths.append(["M10.2,12.2a1.4,1.4 0 1 0 0,0.01 M11.6,12.2v1.6a1.4,1.4 0 0 1 -2.6,0.4", False, True, "1.3", "round", "round", False])
            paths.append(["M13.2,12.3a1.3,1.5 0 0 1 2.6,0v1.6a1.3,1.5 0 0 1 -2.6,0Z", False, True, "1.3", "round", "round", False])
        with open(os.path.join(OUT, name + ".xml"), "w", encoding="utf-8") as f:
            f.write(vector(size, paths))
        print(name)
    # pictogram of the coachmark: a box, an arrow and a wall (not in the sample's symbol set)
    hand = [["M3,9h8v8h-8Z", False, True, "1.8", "round", "round", False],
            ["M12.5,13h6M16,10.5l2.5,2.5 -2.5,2.5", False, True, "1.8", "round", "round", False],
            ["M21,4v17", False, True, "2.4", "round", "round", False]]
    with open(os.path.join(OUT, "ic_hand_drag.xml"), "w", encoding="utf-8") as f:
        f.write(vector(24, hand))
    print("ic_hand_drag")


if __name__ == "__main__":
    main(sys.argv[1])
